# Проба доступа к Ozon из GitHub Actions.
#
# Вопрос один: пропускает ли Ozon запрос, если подделать TLS-отпечаток Chrome.
# Из корпоративной сети это не проверить — там соединение наружу открывает
# шлюз с подменой сертификатов, и Ozon видит его отпечаток, а не наш.
#
# Логи Actions без авторизации не читаются, поэтому результат пишется в
# ozon-test/result.txt и коммитится. Скрипт не падает ни при каком исходе:
# неудача — тоже результат, его надо сохранить.

import datetime
import re
import traceback

АРТИКУЛ = "2713608672"
СТРАНИЦА = f"https://ozon.kz/product/{АРТИКУЛ}/"
API = f"https://ozon.kz/api/composer-api.bx/page/json/v2?url=/product/{АРТИКУЛ}/"

строки = []


def записать(текст):
    строки.append(текст)
    print(текст)


def разобрать(имя, ответ):
    тело = ответ.text
    заголовок = re.search(r"<title>(.*?)</title>", тело, re.S)
    заголовок = заголовок.group(1).strip()[:80] if заголовок else "-"
    цены = re.findall(r"(\d[\d   ]{0,8}\d)\s?₸", тело)[:5]
    записать(
        f"{имя}: статус={ответ.status_code} длина={len(тело)} "
        f"артикул_на_странице={АРТИКУЛ in тело} заголовок={заголовок!r} цены={цены}"
    )


def попробовать(имя, адрес, сессия=None, **параметры):
    try:
        if сессия is None:
            from curl_cffi import requests as cr
            ответ = cr.get(адрес, timeout=30, **параметры)
        else:
            ответ = сессия.get(адрес, timeout=30, **параметры)
        разобрать(имя, ответ)
    except Exception as ошибка:
        записать(f"{имя}: ОШИБКА {type(ошибка).__name__}: {str(ошибка)[:200]}")


def главная():
    записать("время " + datetime.datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S") + " UTC")

    # для сравнения: без подделки отпечатка, как обычный скрипт
    попробовать("страница_без_подделки", СТРАНИЦА)

    # разные браузеры: защита может пропускать одни отпечатки и резать другие
    for браузер in ["chrome", "chrome131", "edge101", "safari17_0"]:
        попробовать(f"страница_{браузер}", СТРАНИЦА, impersonate=браузер)

    # внутренний API сайта — им пользуется сама страница
    попробовать("api_chrome", API, impersonate="chrome")

    # сессией: сначала главная, потом товар — защита может выдавать cookie на входе
    try:
        from curl_cffi import requests as cr
        сессия = cr.Session(impersonate="chrome")
        попробовать("сессия_главная", "https://ozon.kz/", сессия=сессия)
        попробовать("сессия_страница", СТРАНИЦА, сессия=сессия)
        попробовать("сессия_api", API, сессия=сессия)
    except Exception as ошибка:
        записать(f"сессия: ОШИБКА {type(ошибка).__name__}: {str(ошибка)[:200]}")


try:
    главная()
except Exception:
    записать("НЕПРЕДВИДЕННАЯ ОШИБКА:\n" + traceback.format_exc())

with open("ozon-test/result.txt", "w", encoding="utf-8") as файл:
    файл.write("\n".join(строки) + "\n")
